"""Render `docs/codemap.md` from `docs/data/codemap.json` and the `dependsOn` clauses of `build.sbt`.

The codemap is a small, generated map of the code for a reader (human or model) that has to find its way in
the repository: the module dependency graph, then a table per module with one row per Scala package (its
responsibility, entry-point symbols by name, the test suites that cover it, and the ADRs and designs that own
it). Hand-edit `docs/data/codemap.json`, never the markdown.

    python3 scripts/render_codemap.py           write docs/codemap.md
    python3 scripts/render_codemap.py --check   fail when the codemap has drifted

`--check` fails when

  * the committed markdown differs from the render,
  * an entry point is not defined (class, trait, object, enum, type, def, val, given) in the direct sources of
    its package,
  * a suite name is not defined under any `src/test`,
  * a package directory under `src/main/scala` has no entry, or an entry names a package that is gone,
  * an ADR or design path does not exist,
  * an entry names a module that `build.sbt` does not define, or two entries name the same package.

Pure standard library; no sbt, no network.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

DATA = "docs/data/codemap.json"
OUTPUT = "docs/codemap.md"
PACKAGE_ROOT = "xyz/kd5ujc/scarab/"
GENERATED = (
    "<!-- GENERATED by scripts/render_codemap.py from docs/data/codemap.json and build.sbt. Do not edit. -->"
)
PROJECT = re.compile(r'^lazy val (\w+) = scarab\("(\w+)"(?:,\s*"([\w-]+)")?\)', re.M)
DEFINITION = r"\b(?:class|trait|object|enum|type|def|val|given)\s+{name}\b"


@dataclass(frozen=True)
class Edge:
    target: str
    compile: bool


@dataclass(frozen=True)
class Package:
    module: str
    path: str
    responsibility: str
    entry_points: tuple[str, ...]
    suites: tuple[str, ...]
    docs: tuple[str, ...]

    @staticmethod
    def of(raw: dict) -> "Package":
        return Package(
            raw["module"], raw["path"], raw["responsibility"], tuple(raw["entryPoints"]),
            tuple(raw["suites"]), tuple(raw["docs"]),
        )


def split_top_level(text: str) -> list[str]:
    """Split on commas that are outside parentheses and string literals."""
    items, depth, quoted, start = [], 0, False, 0
    for i, ch in enumerate(text):
        if ch == '"':
            quoted = not quoted
        elif not quoted and ch in "([":
            depth += 1
        elif not quoted and ch in ")]":
            depth -= 1
        elif not quoted and depth == 0 and ch == ",":
            items.append(text[start:i])
            start = i + 1
    items.append(text[start:])
    return [i.strip() for i in items if i.strip()]


def balanced_after(text: str, open_at: int) -> str:
    depth, quoted = 0, False
    for i in range(open_at, len(text)):
        ch = text[i]
        if ch == '"':
            quoted = not quoted
        elif not quoted and ch == "(":
            depth += 1
        elif not quoted and ch == ")":
            depth -= 1
            if depth == 0:
                return text[open_at + 1:i]
    return text[open_at + 1:]


def parse_build(sbt: str) -> dict[str, list[Edge]]:
    """Module directory -> its `dependsOn` edges (by directory), in build order."""
    projects = list(PROJECT.finditer(sbt))
    directory = {m.group(1): (m.group(3) or m.group(2)) for m in projects}
    graph: dict[str, list[Edge]] = {}
    for n, m in enumerate(projects):
        end = projects[n + 1].start() if n + 1 < len(projects) else len(sbt)
        block = sbt[m.end():end]
        at = block.find(".dependsOn(")
        edges: list[Edge] = []
        if at >= 0:
            for item in split_top_level(balanced_after(block, at + len(".dependsOn"))):
                name, _, config = (part.strip() for part in item.partition("%"))
                if name not in directory:
                    continue
                edges.append(Edge(directory[name], not config or "compile->compile" in config))
        graph[directory[m.group(1)]] = edges
    return graph


def graph_lines(graph: dict[str, list[Edge]]) -> list[str]:
    width = max(len(m) for m in graph)
    lines = []
    for module, edges in graph.items():
        main = [e.target for e in edges if e.compile]
        test_only = [e.target for e in edges if not e.compile]
        text = ", ".join(main) if main else "(none)"
        if test_only:
            text += "; test only: " + ", ".join(test_only)
        lines.append(f"{module.ljust(width)} -> {text}")
    return lines


def doc_label(path: str) -> str:
    stem = PurePosixPath(path).stem
    if path.startswith("docs/adr/"):
        return "ADR " + stem.split("-")[0]
    if path.startswith("docs/design/"):
        return "design " + stem
    return stem


def cell(values: tuple[str, ...], fmt) -> str:
    return ", ".join(fmt(v) for v in values)


def render(graph: dict[str, list[Edge]], modules: dict[str, str], packages: list[Package]) -> str:
    out = [
        GENERATED, "", "# Code map", "",
        "A generated map of the code: which module depends on which, then each Scala package with its "
        "responsibility, entry points, covering test suites and owning decisions. Entry points are names; "
        "search for them. Edit `docs/data/codemap.json`, then run `python3 scripts/render_codemap.py`; "
        "CI runs it with `--check`.",
        "", "## Module dependencies", "",
        "Derived from `dependsOn` in `build.sbt`; an arrow points at what the module builds on.", "",
        "```", *graph_lines(graph), "```",
    ]
    for module in graph:
        rows = [p for p in packages if p.module == module]
        out += ["", f"## {module}", "", modules.get(module, "").rstrip(".") + "."]
        if not rows:
            out += ["", "No main sources."]
            continue
        out += ["", "| Package | Responsibility | Entry points | Suites | Decisions |", "|---|---|---|---|---|"]
        for p in rows:
            docs = cell(p.docs, lambda d: f"[{doc_label(d)}]({d.removeprefix('docs/')})")
            out.append(
                f"| {p.path} | {p.responsibility} | {cell(p.entry_points, lambda s: f'`{s}`')} "
                f"| {cell(p.suites, lambda s: f'`{s}`')} | {docs} |"
            )
    return "\n".join(out) + "\n"


def discover(root: Path) -> set[tuple[str, str]]:
    found = set()
    for src in sorted(root.glob("*/src/main/scala")):
        for scala in src.rglob("*.scala"):
            relative = scala.parent.relative_to(src).as_posix()
            found.add((src.parts[-4], strip_root(relative)))
    return found


def strip_root(relative: str) -> str:
    prefix = PACKAGE_ROOT
    return relative[len(prefix):] if relative.startswith(prefix) else relative


def package_dir(root: Path, p: Package) -> Path:
    base = root / p.module / "src/main/scala"
    rooted = base / PACKAGE_ROOT / p.path
    return rooted if rooted.is_dir() else base / p.path


def package_source(root: Path, p: Package) -> str:
    directory = package_dir(root, p)
    return "\n".join(f.read_text(encoding="utf-8") for f in sorted(directory.glob("*.scala"))) if directory.is_dir() else ""


def test_source(root: Path) -> str:
    return "\n".join(f.read_text(encoding="utf-8") for f in sorted(root.glob("*/src/test/**/*.scala")))


def problems(root: Path, data: dict, graph: dict[str, list[Edge]]) -> list[str]:
    packages = [Package.of(raw) for raw in data["packages"]]
    found: list[str] = []
    seen: set[tuple[str, str]] = set()
    for p in packages:
        key = (p.module, p.path)
        if key in seen:
            found.append(f"duplicate entry {p.module}:{p.path}")
        seen.add(key)
        if p.module not in graph:
            found.append(f"{p.module}:{p.path}: module is not defined in build.sbt")
    on_disk = discover(root)
    for module, path in sorted(on_disk - seen):
        found.append(f"{module}:{path}: package directory has no codemap entry")
    for module, path in sorted(seen - on_disk):
        found.append(f"{module}:{path}: entry names a package that is gone")
    tests = test_source(root)
    for p in packages:
        if (p.module, p.path) not in on_disk:
            continue
        sources = package_source(root, p)
        for symbol in p.entry_points:
            if not re.search(DEFINITION.format(name=re.escape(symbol)), sources):
                found.append(f"{p.module}:{p.path}: entry point {symbol} is not defined in the package")
        for suite in p.suites:
            if not re.search(DEFINITION.format(name=re.escape(suite)), tests):
                found.append(f"{p.module}:{p.path}: suite {suite} does not exist under src/test")
        for doc in p.docs:
            if not (root / doc).is_file():
                found.append(f"{p.module}:{p.path}: {doc} does not exist")
    return found


def build(root: Path) -> tuple[dict, dict[str, list[Edge]], str]:
    data = json.loads((root / DATA).read_text(encoding="utf-8"))
    graph = parse_build((root / "build.sbt").read_text(encoding="utf-8"))
    text = render(graph, data["modules"], [Package.of(raw) for raw in data["packages"]])
    return data, graph, text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the codemap has drifted")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(argv)
    data, graph, text = build(args.root)
    target = args.root / OUTPUT
    if not args.check:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT} ({text.count(chr(10))} lines)")
        return 0
    found = problems(args.root, data, graph)
    if not target.is_file() or target.read_text(encoding="utf-8") != text:
        found.append(f"{OUTPUT} differs from the render; run python3 scripts/render_codemap.py")
    for line in found:
        print(f"codemap: {line}", file=sys.stderr)
    if not found:
        print(f"codemap ok: {len(data['packages'])} packages, {len(graph)} modules")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
