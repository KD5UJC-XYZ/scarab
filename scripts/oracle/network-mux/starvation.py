"""Export actual pinned Uneven inputs and original Mux starvation-property outcomes offline."""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

from lifecycle import relative_argv, PIN, SOURCE, SOURCE_SHA, HERE, sha, replace_once


def instrument(original: str) -> str:
    if hashlib.sha256(original.encode()).hexdigest() != SOURCE_SHA:
        raise ValueError("pinned Test.Mux source hash mismatch")
    text = replace_once(original, "module Test.Mux (tests) where",
                        "module Test.Mux (tests, exportStarvationCases) where")
    text = replace_once(text, "import Codec.Serialise (Serialise (..))",
                        "import Codec.Serialise (Serialise (..), serialise)")
    text = replace_once(text, "import Data.List (dropWhileEnd, nub)",
                        "import Data.List (dropWhileEnd, intercalate, nub)")
    text = replace_once(text, "import System.IOManager\n", "import System.IOManager\n"
                        "import System.IO (withFile, IOMode (WriteMode), hPutStrLn)\n"
                        "import Numeric (showHex)\n"
                        "import Test.QuickCheck.Gen (unGen)\n"
                        "import Test.QuickCheck.Random (mkQCGen)\n")
    text = replace_once(text, "prop_mux_starvation (Uneven response0 response1) =",
                        "prop_mux_starvation = prop_mux_starvationObserved (\\_ -> pure ())\n\n"
                        "prop_mux_starvationObserved :: ([Mx.MiniProtocolNum] -> IO ()) -> Uneven -> Property\n"
                        "prop_mux_starvationObserved observe (Uneven response0 response1) =")
    text = replace_once(text, "    return $ res_short .&&. res_long .&&. fair",
                        "    observe es\n    return $ res_short .&&. res_long .&&. fair")
    return text + "\n" + (HERE / "starvation-observer.hs").read_text()


def recipe(payload: bytes) -> tuple[str, str, str]:
    """Lossless storage of genLargeByteString's original repeated <=1024-byte chunk."""
    chunk = payload[:1024]
    repeated = (chunk * ((len(payload) + len(chunk) - 1) // len(chunk)))[:len(payload)] if chunk else b""
    if repeated != payload:
        raise ValueError("generated bytes are not the original chunk repetition")
    return str(len(payload)), chunk.hex(), hashlib.sha256(payload).hexdigest()


def normalize(row: list[str]) -> list[str]:
    if len(row) != 11 or row[0] != "mux-starvation-raw-v1":
        raise ValueError("invalid native observation schema")
    a, b, request, wire_a, wire_b = (bytes.fromhex(value) for value in row[4:9])
    eligible = len(a) > 2560 and len(b) > 2560
    if row[10] not in ("pass", "precondition-discard", "upstream-failure"):
        raise ValueError("unknown native verdict")
    if (row[10] == "precondition-discard") == eligible:
        raise ValueError("native implication/outcome mismatch")
    prefixes = []
    for payload, wire in [(a, wire_a), (b, wire_b)]:
        if not wire.endswith(payload):
            raise ValueError("native serialization does not retain original payload")
        prefixes.append(wire[:len(wire) - len(payload)].hex())
    trace = [] if not row[9] else list(map(int, row[9].split(',')))
    if len(trace) > 100 or any(n not in (2, 3) for n in trace):
        raise ValueError("invalid original receive-header trace")
    # Native prop_mux_starvation intentionally remains untouched: both replies use response1.
    local = ("precondition-discard" if not eligible else
             "unsupported-message-limit" if len(wire_b) > 2500000 else "applicable")
    return ["mux-starvation-v1", *row[1:4], *recipe(a), *recipe(b), request.hex(),
            prefixes[0], prefixes[1], hashlib.sha256(wire_a).hexdigest(),
            hashlib.sha256(wire_b).hexdigest(), row[9], row[10], local]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", required=True, type=Path)
    p.add_argument("--probe-dir", required=True, type=Path)
    p.add_argument("--output-dir", required=True, type=Path)
    p.add_argument("--cache-build", type=Path)
    p.add_argument("--image", default="scarab-v02-49-protocols-cache:peer-acceptance-20261019")
    p.add_argument("--container", default="scarab-262-mux-starvation")
    p.add_argument("--count", type=int, default=32)
    p.add_argument("--seed", type=int, default=512001)
    a = p.parse_args()
    if not 8 <= a.count <= 64:
        p.error("count must be 8..64")
    probe = a.probe_dir.resolve()
    probe.mkdir(parents=True, exist_ok=True)
    commands = []

    def run(argv: list[str]) -> str:
        log = probe / f"command-{len(commands)}.log"
        with log.open("w") as out:
            result = subprocess.run(argv, stdout=out, stderr=subprocess.STDOUT, text=True)
        commands.append({"argv": relative_argv(argv), "returncode": result.returncode, "logSha256": sha(log)})
        (probe / "commands.json").write_text(json.dumps(commands, indent=2) + "\n")
        if result.returncode:
            raise RuntimeError(f"command failed ({result.returncode}); see {log}")
        return log.read_text().strip()

    source = a.source.resolve()
    if run(["git", "-C", str(source), "rev-parse", "HEAD"]) != PIN:
        raise ValueError("upstream pin mismatch")
    overlay = probe / "source"
    if overlay.exists():
        raise ValueError("use a fresh probe directory")
    archive = probe / "source.tar"
    run(["git", "-C", str(source), "archive", "--format=tar", "-o", str(archive), PIN])
    overlay.mkdir()
    run(["tar", "-xf", str(archive), "-C", str(overlay)])
    archive.unlink()
    original = (overlay / SOURCE).read_text()
    (overlay / SOURCE).write_text(instrument(original))
    main_path = "network-mux/test/Main.hs"
    old_main = (overlay / main_path).read_text()
    main = replace_once(old_main, "import Test.Mux qualified (tests)",
                        "import Test.Mux qualified (tests, exportStarvationCases)\nimport System.Environment (getArgs)")
    main = replace_once(main, "main = defaultMain tests",
                        'main = getArgs >>= \\args -> case args of\n'
                        '  ["--export-starvation", path, count, seed] -> Test.Mux.exportStarvationCases path (read count) (read seed)\n'
                        '  _ -> defaultMain tests')
    (overlay / main_path).write_text(main)
    patch = "".join("".join(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                             fromfile="a/" + path, tofile="b/" + path))
                    for path, old, new in [(SOURCE, original, (overlay / SOURCE).read_text()),
                                            (main_path, old_main, main)])
    (probe / "observer.patch").write_text(patch)
    build = probe / "builddir"
    if a.cache_build:
        shutil.copytree(a.cache_build, build)
    created = False
    try:
        run(["docker", "create", "--network=none", "--name", a.container,
             "--entrypoint", "tail", "-v", f"{overlay}:/source", "-v", f"{probe}:/probe",
             "-w", "/source", a.image, "-f", "/dev/null"])
        created = True
        run(["docker", "start", a.container])
        image = run(["docker", "inspect", a.container, "--format", "{{.Image}}"])
        base = ["docker", "exec", "-w", "/source", a.container]
        run(base + ["cabal", "build", "--offline", "network-mux:test:test", "--builddir=/probe/builddir", "--jobs=1"])
        binary = run(base + ["cabal", "list-bin", "network-mux:test:test", "--builddir=/probe/builddir"]).splitlines()[-1]
        run(base + [binary, "--export-starvation", "/probe/raw.tsv", str(a.count), str(a.seed)])
        raw = probe / "raw.tsv"
        rows = [normalize(line.split("\t")) for line in raw.read_text().splitlines()]
        if len(rows) != a.count:
            raise ValueError("missing native observations")
        output = probe / "starvation.tsv"
        output.write_text("".join("\t".join(row) + "\n" for row in rows))
        manifest = {
            "schema": "scarab-upstream-mux-starvation-v1", "sourceCommit": PIN,
            "sourcePath": SOURCE, "sourceFileSha256": SOURCE_SHA,
            "seed": a.seed, "count": a.count, "sizeRule": "30 + ordinal mod 11",
            "generator": "unchanged Arbitrary Uneven; no seed filtering or resizing",
            "nativeProperty": "prop_mux_starvation; unchanged implication, wiring and ordering assertion",
            "nativeWiring": "response1 on both protocols; response0 used in original precondition",
            "storage": "lossless <=1024-byte repeated-chunk recipe validated against complete native hex",
            "sha256": sha(output), "rawExportSha256": sha(raw), "observerPatchSha256": sha(probe / "observer.patch"),
            "observerSourceSha256": sha(HERE / "starvation-observer.hs"),
            "patchedSourceSha256": sha(overlay / SOURCE), "patchedMainSha256": sha(overlay / main_path),
            "executableSha256": run(base + ["sha256sum", binary]).split()[0],
            "planSha256": sha(build / "cache/plan.json"), "projectSha256": sha(overlay / "cabal.project"),
            "image": a.image, "imageDigest": image, "network": "none", "commands": commands.copy(),
            "nativeOutcomes": {k: sum(r[-2] == k for r in rows) for k in ["pass", "precondition-discard", "upstream-failure"]},
            "localDomains": {k: sum(r[-1] == k for r in rows) for k in ["applicable", "precondition-discard", "unsupported-message-limit"]},
            "nativeTraceBothProtocols": sum(set(r[15].split(',')) == {"2", "3"} for r in rows),
        }
        a.output_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(output, a.output_dir / output.name)
        shutil.copy2(probe / "observer.patch", a.output_dir / "observer.patch")
        (a.output_dir / "starvation.tsv.manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
        print(json.dumps({k: manifest[k] for k in ["count", "nativeOutcomes", "localDomains", "sha256"]}))
    finally:
        if created:
            run(["docker", "rm", "-f", a.container])


if __name__ == "__main__":
    main()
