/** Actual native answers and native state at one acquired point, not answers regenerated by Scarab.
  */
class WalletPeerReferenceSuite extends FunSuite:
  private val root = Path.of("fixtures/reference/ntc-wallet-peers-11.1.3")
  private def json(path: Path): Json =
    parse(Files.readString(path)).fold(e => fail(e.message), identity)
  private def hex(value: String): Bytes = Bytes.fromHex(value).fold(e => fail(e.message), identity)

  private final case class Native(nes: NewEpochState[Conway], setup: NodeSetup)
  private given ChainRead[Native] with
    extension (native: Native)
      def provenance: MirrorProvenance = MirrorProvenance.complete
      def era: Era = Era.Conway
      def ledgerEpoch: BigInt = native.nes.epoch.toBigInt
      def protocol: ProtocolState = native.setup.mirrorStart.protocol
      def consensus: ConsensusExtras = native.setup.mirrorStart.consensus
      def plutus: PlutusStats = PlutusStats.zero
      def utxo: Utxo = native.nes.es.ls.utxo.utxo.utxo
      def ledger(at: Option[BlockRef]): Read[Option[InEra]] =
        Right(
          Some(
            InEra.Of(
              ShelleyBasedEra.SConway,
              new MirrorEraRead(native.nes)(using ShelleyBasedEra.SConway)
            )
          )
        )

  private final case class Fixture(
      name: String,
      state: Native,
      env: QueryEnv,
      view: QueryView[Native],
      queries: Vector[Json]
  )
  private val entries = json(root.resolve("manifest.json")).hcursor
    .get[Vector[Json]]("cases")
    .fold(e => fail(e.message), identity)
  private val fixtures = entries.map { entry =>
    val cursor = entry.hcursor
    val name = cursor.get[String]("name").fold(e => fail(e.message), identity)
    val dir = root.resolve(name)
    val setup =
      NodeSetup.fromDirectory(dir.resolve("genesis")).fold(e => fail(e.message), identity)
    val nes = HaskellState
      .decode[Conway](Bytes.fromArray(Files.readAllBytes(dir.resolve("new-epoch-state.cbor"))))(
        using ShelleyBasedEra.SConway
      )
      .fold(e => fail(e.toString), identity)
    val state = Native(nes, setup)
    val slot = cursor.downField("point").get[BigInt]("slot").fold(e => fail(e.message), identity)
    val hash = cursor.downField("point").get[String]("hash").fold(e => fail(e.message), identity)
    val point = Point.Block(UInt64.saturating(slot), hex(hash))
    val env = QueryEnv(
      setup.geometry.systemStart,
      setup.geometry,
      setup.praos.forks,
      setup.byronParams.fold(EraHistory.ByronParams(50, 1000, 5))(p =>
        EraHistory.ByronParams(p.epochSlots, BigInt(p.slotLengthMillis), BigInt(p.securityParam))
      ),
      setup.globals.maxSupply,
      setup.genesis.raw,
      setup.mirrorEnv().ledger,
      networkMagic = setup.genesis.networkMagic.toLong
    )
    val queries =
      json(dir.resolve("queries.json")).as[Vector[Json]].fold(e => fail(e.message), identity)
    Fixture(name, state, env, QueryView(point, None, state), queries)
  }

  test("all 69 original native messages retain their recorded input and reply-file hashes") {
    assertEquals(fixtures.map(_.queries.size).sum, 69)
    def digest(path: Path): String =
      MessageDigest
        .getInstance("SHA-256")
        .digest(Files.readAllBytes(path))
        .map("%02x".format(_))
        .mkString
    entries.foreach { entry =>
      val cursor = entry.hcursor
      val name = cursor.get[String]("name").fold(e => fail(e.message), identity)
      val dir = root.resolve(name)
      Vector("new-epoch-state.cbor" -> "newEpochStateSha256", "queries.json" -> "queriesSha256")
        .foreach { (file, field) =>
          assertEquals(
            digest(dir.resolve(file)),
            cursor.get[String](field).fold(e => fail(e.message), identity)
          )
        }
      cursor
        .get[Map[String, String]]("genesisSha256")
        .fold(e => fail(e.message), identity)
        .foreach { (file, sha) =>
          assertEquals(digest(dir.resolve("genesis").resolve(file)), sha)
        }
    }
  }

  fixtures.foreach { fixture =>
    fixture.queries.foreach { entry =>
      val c = entry.hcursor
      val label = c.get[String]("label").fold(e => fail(e.message), identity)
      val versionNumber = c.get[Int]("version").fold(e => fail(e.message), identity)
      test(s"${fixture.name}: $label at NTC $versionNumber equals the original native message") {
        val version = NtcVersion
          .fromNumber(versionNumber)
          .getOrElse(fail(s"unknown NTC version $versionNumber"))
        val request = hex(c.get[String]("requestHex").fold(e => fail(e.message), identity))
        val expected = hex(c.get[String]("replyHex").fold(e => fail(e.message), identity))
        val query = NtcQuery.decode(request, version).fold(e => fail(e.toString), identity)
        val answer = QueryAnswers
          .answerOrWhy(fixture.env, fixture.view, Map.empty, query, version)
          .fold(e => fail(e.toString), identity)
        assertEquals(CborOut.build(_.array(2).uint(4).raw(answer)), expected)
      }
    }
  }

  test("native fixtures contain both nonempty relays and genuinely nonzero member rewards") {
    val peers = fixtures.find(_.name == "peer-relays").getOrElse(fail("missing peer fixture"))
    assert(
      peers.state.nes.es.ls.cert.pState.stakePools.valuesIterator.exists(p =>
        xyz.kd5ujc.scarab.ledger.PoolRelays.decode(p.relays).exists(_.nonEmpty)
      )
    )
    val rewards =
      fixtures.find(_.name == "reward-history").getOrElse(fail("missing reward fixture"))
    assert(rewards.state.nes.es.nonMyopic.rewardPot.value > 0)
    assert(rewards.state.nes.es.nonMyopic.likelihoods.nonEmpty)
    val query = rewards.queries
      .find(_.hcursor.get[String]("label").contains("NonMyopic-members"))
      .getOrElse(fail("missing member query"))
    val message = Cbor
      .decode(hex(query.hcursor.get[String]("replyHex").fold(e => fail(e.message), identity)))
      .fold(e => fail(e.toString), identity)
    val amounts = message.value match
      case Value.Arr(Vector(_, wrapped)) =>
        wrapped.value match
          case Value.Arr(Vector(rewards)) =>
            rewards.value match
              case Value.Map(members) =>
                members.flatMap { (_, pools) =>
                  pools.value match
                    case Value.Map(values) =>
                      values.map { (_, coin) =>
                        coin.value match
                          case Value.UInt(value) => value
                          case other             => fail(s"expected reward coin, got $other")
                      }
                    case other => fail(s"expected pool rewards, got $other")
                }
              case other => fail(s"expected member rewards, got $other")
          case other => fail(s"expected successful HFC result, got $other")
      case other => fail(s"expected MsgResult, got $other")
    assert(amounts.exists(_ > 0), "fixture must exercise the nonzero member reward formula")
  }

  test("malformed stored relay bytes refuse the complete snapshot rather than omitting a pool") {
    val fixture = fixtures.find(_.name == "peer-relays").getOrElse(fail("missing peer fixture"))
    val (id, pool) = fixture.state.nes.es.ls.cert.pState.stakePools.headOption
      .getOrElse(fail("native fixture has no pools"))
    val changed = ConwayLedgerState.pools.modify(
      _.updated(id, pool.copy(relays = hex("00")))
    )(fixture.state.nes.es.ls)
    val nes = fixture.state.nes.copy(es = fixture.state.nes.es.copy(ls = changed))
    val view = fixture.view.copy(state = fixture.state.copy(nes = nes))
    val query =
      NtcQuery.IfCurrent(Era.Conway.index, LedgerQuery.GetLedgerPeerSnapshot(LedgerPeerKind.All))
    assertEquals(
      QueryAnswers.answerOrWhy(fixture.env, view, Map.empty, query),
      Left(
        Unanswered.StoredRelays(
          NonEmptyVector.one(SkippedPool(id.bytes, PoolRelayError.NotASequence))
        )
      )
    )
  }

  private def rich: Fixture =
    fixtures.find(_.name == "reward-later").getOrElse(fail("missing later reward fixture"))
  private def facts(nes: NewEpochState[Conway]): ConwayFacts =
    new ConwayFacts(new MirrorEraRead(nes)(using ShelleyBasedEra.SConway))
  private def coin(value: BigInt): xyz.kd5ujc.scarab.ledger.state.Coin =
    xyz.kd5ujc.scarab.ledger.state.Coin.fromBigInt(value).fold(e => fail(e.toString), identity)

  private def result(nes: NewEpochState[Conway], query: LedgerQuery): Either[Unanswered, Bytes] =
    val view = rich.view.copy(state = rich.state.copy(nes = nes))
    QueryAnswers
      .answerOrWhy(rich.env, view, Map.empty, NtcQuery.IfCurrent(Era.Conway.index, query))
      .map { encoded =>
        Cbor
          .decode(encoded, Cbor.Limits(allowFloats = true))
          .fold(e => fail(e.toString), identity)
          .value match
          case Value.Arr(Vector(value)) => value.original
          case other                    => fail(s"expected successful HFC result, got $other")
      }

  private def memberRewards(
      nes: NewEpochState[Conway],
      input: Either[BigInt, xyz.kd5ujc.scarab.ledger.Credential]
  ): Map[Bytes, BigInt] =
    val encoded = result(nes, LedgerQuery.GetNonMyopicMemberRewards(Vector(input)))
      .fold(e => fail(e.toString), identity)
    Cbor.decode(encoded).fold(e => fail(e.toString), identity).value match
      case Value.Map(Vector((_, pools))) =>
        pools.value match
          case Value.Map(entries) =>
            entries.map { (id, amount) =>
              val key = id.value match
                case Value.ByteString(bytes) => bytes
                case other                   => fail(s"expected pool id, got $other")
              val value = amount.value match
                case Value.UInt(n) => n
                case other         => fail(s"expected bounded reward in this control, got $other")
              key -> value
            }.toMap
          case other => fail(s"expected pool rewards, got $other")
      case other => fail(s"expected one member's rewards, got $other")

  private def params(
      nes: NewEpochState[Conway],
      update: xyz.kd5ujc.scarab.ledger.ProtocolParams => xyz.kd5ujc.scarab.ledger.ProtocolParams
  ): NewEpochState[Conway] =
    val ls = ConwayLedgerState.gov.modify(g => g.copy(curPParams = update(g.curPParams)))(nes.es.ls)
    nes.copy(es = nes.es.copy(ls = ls))

  test("unit control: zero nOpt uses the native one-pool fallback in monetary calculations") {
    val noHistory = rich.state.nes.copy(es =
      rich.state.nes.es.copy(nonMyopic =
        rich.state.nes.es.nonMyopic.copy(likelihoods = xyz.kd5ujc.scarab.ledger.state.Sorted.empty)
      )
    )
    val zero = memberRewards(params(noHistory, _.copy(nOpt = 0)), Left(BigInt(1000000000)))
    val one = memberRewards(params(noHistory, _.copy(nOpt = 1)), Left(BigInt(1000000000)))
    assert(zero.values.exists(_ > 0), "fallback control must compute actual rewards")
    assertEquals(zero, one)
  }

  test("unit control: equal desirability selects the first pool in native key order") {
    import xyz.kd5ujc.scarab.codec.Rational
    import xyz.kd5ujc.scarab.ledger.state.{Likelihood, LogWeight, Sorted}
    val ls = ConwayLedgerState.pools.modify(
      _.transform((_, pool) =>
        pool.copy(pledge = coin(0), cost = coin(100000000), margin = Rational.zero)
      )
    )(rich.state.nes.es.ls)
    val history = Sorted.map(
      ls.cert.pState.stakePools.keysIterator.map(id =>
        id -> Likelihood(Vector.fill(100)(LogWeight(0.0f)))
      )
    )
    val base = rich.state.nes.copy(es =
      rich.state.nes.es
        .copy(ls = ls, nonMyopic = rich.state.nes.es.nonMyopic.copy(likelihoods = history))
    )
    val nes = params(base, _.copy(nOpt = 1, a0 = Rational.zero))
    val first = ls.cert.pState.stakePools.headOption.fold(fail("no pools"))(_._1.bytes)
    val rewards = memberRewards(nes, Left(BigInt(1000000000)))
    assert(rewards.size > 1)
    assert(
      rewards.iterator.filter(_._1 != first).forall(_._2 < rewards(first)),
      "only the first equal-desirability pool receives the top-pool stake assumption"
    )
  }

  test(
    "unit control: an unmet pledge produces zero while other pools still receive member rewards"
  ) {
    val before = facts(rich.state.nes).currentStake.fold(e => fail(e.toString), identity)
    val (id, snapshot) = before.pools.headOption.getOrElse(fail("no pools"))
    val ls = ConwayLedgerState.pools.modify(pools =>
      pools.updatedWith(id)(
        _.map(_.copy(pledge = coin(snapshot.selfDelegatedOwnersStake.value + 1)))
      )
    )(rich.state.nes.es.ls)
    val nes = rich.state.nes.copy(es = rich.state.nes.es.copy(ls = ls))
    val rewards = memberRewards(nes, Left(BigInt(1000000000)))
    assertEquals(rewards(id.bytes), BigInt(0))
    assert(rewards.iterator.filter(_._1 != id.bytes).exists(_._2 > 0))
  }

  test("unit control: an absent credential retains all pools with zero member rewards") {
    val missing = xyz.kd5ujc.scarab.ledger.Credential.Key(hex("ff" * 28))
    val rewards = memberRewards(rich.state.nes, Right(missing))
    assertEquals(rewards.size, rich.state.nes.es.ls.cert.pState.stakePools.size)
    assert(rewards.values.forall(_ == 0))
  }

  test("unit control: native Integer outputs retain reward pots and costs beyond uint64") {
    val large = BigInt(1) << 80
    val ls = ConwayLedgerState.pools.modify(
      _.transform((_, pool) => pool.copy(cost = coin(large)))
    )(rich.state.nes.es.ls)
    val nes = rich.state.nes.copy(es =
      rich.state.nes.es
        .copy(ls = ls, nonMyopic = rich.state.nes.es.nonMyopic.copy(rewardPot = coin(large)))
    )
    val encoded = result(nes, LedgerQuery.GetRewardInfoPools).fold(e => fail(e.toString), identity)
    val decoded =
      Cbor.decode(encoded, Cbor.Limits(allowFloats = true)).fold(e => fail(e.toString), identity)
    val expected = CborOut.build(_.integer(large))
    decoded.value match
      case Value.Arr(Vector(parameters, pools)) =>
        parameters.value match
          case Value.Arr(Vector(_, _, pot, _)) => assertEquals(pot.original, expected)
          case other                           => fail(s"expected reward parameters, got $other")
        pools.value match
          case Value.Map(entries) =>
            entries.foreach { (_, pool) =>
              pool.value match
                case Value.Arr(Vector(_, _, _, cost, _, _)) => assertEquals(cost.original, expected)
                case other => fail(s"expected reward pool info, got $other")
            }
          case other => fail(s"expected pools, got $other")
      case other => fail(s"expected reward info result, got $other")
  }

  test("unit control: invalid bounded-ratio components return an unwritable answer") {
    import xyz.kd5ujc.scarab.codec.Rational
    val badA0 = params(rich.state.nes, _.copy(a0 = Rational(1, BigInt(1) << 64)))
    assertEquals(result(badA0, LedgerQuery.GetRewardInfoPools), Left(Unanswered.Unwritable))
    val ls = ConwayLedgerState.pools.modify(
      _.transform((_, pool) => pool.copy(margin = Rational(2)))
    )(rich.state.nes.es.ls)
    val badMargin = rich.state.nes.copy(es = rich.state.nes.es.copy(ls = ls))
    assertEquals(result(badMargin, LedgerQuery.GetRewardInfoPools), Left(Unanswered.Unwritable))
    assertEquals(
      result(badMargin, LedgerQuery.GetNonMyopicMemberRewards(Vector(Left(BigInt(1000000000))))),
      Left(Unanswered.Unwritable)
    )
  }
